def project_transport_failure(value, *, source_pins=None):
    """Project bounded source coordinates as evidence, never execution authority."""
    fields = {'schema', 'failure_category', 'substage', 'original_type', 'original_code',
        'terminal_observed', 'source_identity_sha256', 'source_frames', 'omitted_frames',
        'unadmitted_frames', 'traceback_truncated', 'raw_error_recorded', 'locals_recorded', 'frame_basis'}
    if (type(value) is not dict or set(value) != fields
            or value['schema'] != 'radik.plan_transport_failure.v01'
            or not _closed(value['failure_category'], TRANSPORT_FAILURE_CATEGORIES)
            or not _closed(value['substage'], TRANSPORT_FAILURE_SUBSTAGES)
            or not _closed(value['original_type'], SAFE_ERROR_TYPES)
            or not _closed(value['original_code'], OWNED_ERROR_CODES | MEMORY_ERROR_CODES | RETURN_ERROR_CODES | {'SANITIZED_OPERATION_FAILURE'})
            or type(value['terminal_observed']) is not bool
            or type(value['traceback_truncated']) is not bool
            or value['raw_error_recorded'] is not False or value['locals_recorded'] is not False
            or value['frame_basis'] != 'SOURCE_VALIDATOR_PINS_CAPTURED_BEFORE_RESERVATION'
            or type(value['source_frames']) is not list or len(value['source_frames']) > 32
            or any(type(value[key]) is not int or not 0 <= value[key] <= 128
                for key in ('omitted_frames', 'unadmitted_frames'))):
        return None
    def sha(item):
        return type(item) is str and len(item) == 64 and all(char in '0123456789abcdef' for char in item)
    if not sha(value['source_identity_sha256']):
        return None
    if ((value['failure_category'] == 'PRETERMINAL_UNCERTAIN' and value['terminal_observed'])
            or (value['failure_category'] == 'POSTTERMINAL_LOCAL' and not value['terminal_observed'])):
        return None
    frames = []
    for frame in value['source_frames']:
        if type(frame) is not dict or set(frame) != {'path', 'sha256', 'line', 'function'}:
            return None
        name, function = frame['path'], frame['function']
        if (type(name) is not str or not 1 <= len(name) <= 1024 or not name.endswith('.py')
                or '\\' in name or any(part in ('', '.', '..', 'private', '.git', '.codex', '.aws', 'Arena', 'arena',
                    'local_operator', 'local_operator_private') or part.startswith(('.env', '.venv')) for part in name.split('/'))
                or not sha(frame['sha256']) or type(frame['line']) is not int or not 1 <= frame['line'] <= 1000000
                or type(function) is not str or not 1 <= len(function) <= 96
                or not (function in TRANSPORT_FRAME_FUNCTIONS or function.isascii() and function.isidentifier())):
            return None
        if source_pins is not None and (type(source_pins) is not dict or source_pins.get(name) != frame['sha256']):
            return None
        frames.append(dict(frame))
    return dict(value, source_frames=frames)


def _closed(value, choices):
    return type(value) is str and value in choices


def _attribute(error, key, default=None):
    try:return getattr(error, key, default)
    except BaseException:return default


def _name(error):
    value = type(error).__name__
    return value if value in SAFE_ERROR_TYPES else "Exception"


def _code(error):
    value = None
    if type(error) is ValueError and len(error.args) == 1 and type(error.args[0]) is str:
        value = error.args[0]
    elif type(error).__name__ in TYPED_GUARD_NAMES:
        candidate = _attribute(error, "code")
        if type(candidate) is str:
            value = candidate
    return value if _closed(value, OWNED_ERROR_CODES | MEMORY_ERROR_CODES | RETURN_ERROR_CODES) else "SANITIZED_OPERATION_FAILURE"


def _secondary_valid(value):
    return (type(value) is dict and set(value) == _CORE_FIELDS
        and _closed(value["type"], SAFE_ERROR_TYPES)
        and _closed(value["code"], OWNED_ERROR_CODES | MEMORY_ERROR_CODES | RETURN_ERROR_CODES | {"SANITIZED_OPERATION_FAILURE"})
        and _closed(value["phase"], PHASES) and _closed(value["step"], STEPS)
        and value["raw_error_recorded"] is False)


def _state(error):
    value = _attribute(error, _STATE_KEY)
    fields = {"phase", "step", "primary_persistence", "secondary_failures", "secondary_failures_omitted", "primary_printed"}
    if (type(value) is not dict or set(value) != fields or not _closed(value["phase"], PHASES)
            or not _closed(value["step"], STEPS) or not _closed(value["primary_persistence"], PERSISTENCE_STATES)
            or type(value["secondary_failures"]) is not list
            or len(value["secondary_failures"]) > MAX_SECONDARY_FAILURES
            or not all(_secondary_valid(row) for row in value["secondary_failures"])
            or type(value["primary_printed"]) is not bool
            or type(value["secondary_failures_omitted"]) is not int
            or not 0 <= value["secondary_failures_omitted"] <= 1000000):
        return None
    return value


def project_error(error, *, phase=None, step=None):
    """Return closed diagnostics; exception text and arbitrary metadata stay private."""
    state = _state(error)
    if state is not None:
        phase, step = state["phase"], state["step"]
    result = {"type": _name(error), "code": _code(error),
        "phase": phase if _closed(phase, PHASES) else "UNKNOWN",
        "step": step if _closed(step, STEPS) else "UNKNOWN", "raw_error_recorded": False}
    stream_event = project_stream_event(_attribute(error, "stream_event"))
    if stream_event is not None:
        result["stream_event"] = stream_event
    transport_failure = project_transport_failure(_attribute(error, "transport_failure"))
    if transport_failure is not None:
        result["transport_failure"] = transport_failure
    code = result["code"]
    stage = _attribute(error, "stage")
    if code in MEMORY_ERROR_CODES:
        stages = {"ACCEPTED_RESULT_PREPUBLICATION", "MEMORY_WRITEBACK_VALIDATION", "MEMORY_CONSUMER_VALIDATION"}
        result["stage"] = stage if _closed(stage, stages) else (
            "MEMORY_WRITEBACK_VALIDATION" if code in MEMORY_WRITEBACK_CODES
            else "MEMORY_CONSUMER_VALIDATION")
    elif code in RETURN_ERROR_CODES:
        stages = {"RETURN_PREBUILD", "RETURN_LOCAL_PAIR", "RETURN_DELIVERY", "RETURN_CHECKPOINT"}
        result["stage"] = stage if _closed(stage, stages) else "RETURN_PREBUILD"
    if state is not None:
        result.update(primary_observed=True, primary_preserved=True,
            primary_persistence=state["primary_persistence"],
            secondary_failures=[dict(row) for row in state["secondary_failures"]],
            secondary_failures_omitted=state["secondary_failures_omitted"])
    return result


def observe_failure(error, *, phase, step):
    """Bind the first observed location without replacing exception identity/type."""
    state = _state(error)
    if state is None:
        try:
            setattr(error, _STATE_KEY, {"phase": phase if _closed(phase, PHASES) else "UNKNOWN",
                "step": step if _closed(step, STEPS) else "UNKNOWN", "primary_persistence": "IN_MEMORY_ONLY",
                "secondary_failures": [], "secondary_failures_omitted": 0, "primary_printed": False})
        except BaseException:
            pass
    else:
        # A transport cleanup can precede the enclosing task's first location.
        if state["phase"] == "UNKNOWN" and _closed(phase, PHASES):state["phase"] = phase
        if state["step"] == "UNKNOWN" and _closed(step, STEPS):state["step"] = step
    return project_error(error,phase=phase,step=step)


def record_secondary(primary, secondary, *, phase, step):
    """Append a separate bounded safe cause; never raise or replace the primary."""
    state = _state(primary)
    if state is None:
        observe_failure(primary, phase="UNKNOWN", step=step)
        state = _state(primary)
    projected = project_error(secondary, phase=phase, step=step)
    row = {key: projected[key] for key in _CORE_FIELDS}
    if state is None:
        return dict(project_error(primary,phase="UNKNOWN",step=step),primary_observed=True,
            primary_preserved=True,primary_persistence="IN_MEMORY_ONLY",
            secondary_failures=[row],secondary_failures_omitted=0)
    if len(state["secondary_failures"]) < MAX_SECONDARY_FAILURES:
        state["secondary_failures"].append(row)
    else:
        state["secondary_failures_omitted"] = min(1000000, state["secondary_failures_omitted"] + 1)
    return project_error(primary)


def mark_primary_persisted(error):
    """Call only after exact report bytes were fsynced and read back."""
    state = _state(error)
    if state is not None:
        state["primary_persistence"] = "DURABLE_READBACK_VERIFIED"
    return project_error(error)


def safe_projection(value):
    """Clean a saved projection using the same finite code and context tables."""
    value=value if type(value) is dict else {}
    codes=OWNED_ERROR_CODES | MEMORY_ERROR_CODES | RETURN_ERROR_CODES
    result={"type":value.get("type") if _closed(value.get("type"),SAFE_ERROR_TYPES) else "Exception",
        "code":value.get("code") if _closed(value.get("code"),codes) else "SANITIZED_OPERATION_FAILURE",
        "phase":value.get("phase") if _closed(value.get("phase"),PHASES) else "UNKNOWN",
        "step":value.get("step") if _closed(value.get("step"),STEPS) else "UNKNOWN",
        "raw_error_recorded":False}
    stream_event=project_stream_event(value.get("stream_event"))
    if stream_event is not None:result["stream_event"]=stream_event
    transport_failure=project_transport_failure(value.get("transport_failure"))
    if transport_failure is not None:result["transport_failure"]=transport_failure
    stage=value.get("stage")
    if result["code"] in MEMORY_ERROR_CODES:
        stages={"ACCEPTED_RESULT_PREPUBLICATION","MEMORY_WRITEBACK_VALIDATION","MEMORY_CONSUMER_VALIDATION"}
        result["stage"]=stage if _closed(stage,stages) else "MEMORY_CONSUMER_VALIDATION"
    elif result["code"] in RETURN_ERROR_CODES:
        stages={"RETURN_PREBUILD","RETURN_LOCAL_PAIR","RETURN_DELIVERY","RETURN_CHECKPOINT"}
        result["stage"]=stage if _closed(stage,stages) else "RETURN_PREBUILD"
    if value.get("primary_observed") is True and value.get("primary_preserved") is True:
        result.update(primary_observed=True,primary_preserved=True)
        if _closed(value.get("primary_persistence"),PERSISTENCE_STATES):
            result["primary_persistence"]=value["primary_persistence"]
    secondary=value.get("secondary_failures",[])
    if (type(secondary) is list and len(secondary)<=MAX_SECONDARY_FAILURES
            and all(_secondary_valid(row) for row in secondary)):
        result["secondary_failures"]=[dict(row) for row in secondary]
    else:result["secondary_failures"]=[]
    omitted=value.get("secondary_failures_omitted",0)
    result["secondary_failures_omitted"]=omitted if type(omitted) is int and 0<=omitted<=1000000 else 0
    return result


