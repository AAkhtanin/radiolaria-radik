_STREAM_SCHEMA_V02 = 'radik.public_stream_event_observation.v02'
_STREAM_SCHEMA_V03 = 'radik.public_stream_event_observation.v03'
_STREAM_MAX_OBSERVATION_BYTES = 16384
_STREAM_MAX_PAYLOAD_BYTES = 262144
_STREAM_RECENT_TYPE_COUNT = 8
_STREAM_TOKEN = _stream_re.compile(r'[a-z][a-z0-9_.]{0,95}\Z')
_STREAM_HASH = _stream_re.compile(r'[0-9a-f]{64}\Z')
_STREAM_ID = _stream_re.compile(r'[A-Za-z0-9_-]{1,160}\Z')
_STREAM_SHAPES = ('ABSENT', 'NULL', 'BOOLEAN', 'INTEGER', 'FLOAT', 'STRING', 'ARRAY', 'OBJECT', 'OTHER')
_STREAM_FIELDS = ('type', 'sequence_number', 'response', 'response_id', 'item', 'item_id', 'output_index',
    'content_index', 'summary_index', 'annotation_index', 'part', 'delta', 'text', 'refusal', 'annotation',
    'status', 'logprobs', 'code', 'message', 'param', 'arguments', 'name', 'input', 'command', 'obfuscation')
_STREAM_NAME_STATES = ('ABSENT', 'NULL', 'INVALID_TYPE', 'TOKEN', 'INVALID_TOKEN', 'OVERSIZED', 'INVALID_UTF8')
_STREAM_COUNT_KEYS = ('accepted_events', 'item_count', 'finalized_count', 'text_parts', 'reasoning_parts',
    'summary_parts', 'refusal_parts')
_STREAM_FIELDS_V02 = _STREAM_FIELDS + ('metadata', 'safety_buffering')
_STREAM_METADATA_KEYS = ('type', 'openai_verification_recommendation', 'openai_chatgpt_moderation_metadata',
    'use_cases', 'reasons', 'retry_model')
_STREAM_METADATA_HEADERS = ('openai-model', 'x-openai-model', 'x-codex-turn-state',
    'x-codex-safety-buffering-enabled', 'x-codex-safety-buffering-faster-model')
_STREAM_METADATA_REFUSALS = ('plan_metadata_shape', 'plan_metadata_bound', 'plan_metadata_model_shape',
    'plan_metadata_model_conflict', 'plan_metadata_verification_shape', 'plan_metadata_verification_required',
    'plan_metadata_buffering_shape', 'plan_metadata_control_conflict', 'plan_metadata_control_not_supported')

_STREAM_METADATA_REFUSALS_V03 = tuple(code for code in _STREAM_METADATA_REFUSALS if code != 'plan_metadata_bound') + ('plan_metadata_byte_limit',)


def _stream_canonical(value):
    return _stream_json.dumps(value, sort_keys=True, ensure_ascii=False, separators=(',', ':'), allow_nan=False).encode('utf-8')

def _stream_sha(raw):
    return _stream_hashlib.sha256(raw).hexdigest()


def project_stream_event(value):
    """Return only a strictly validated public record, or None on refusal."""
    try:
        def check(condition):
            if not condition:
                raise ValueError
        def integer(number, maximum):
            return type(number) is int and 0 <= number <= maximum
        def hashed(item):
            return type(item) is str and _STREAM_HASH.fullmatch(item) is not None
        def name(item):
            check(type(item) is dict and set(item) == {'state', 'token', 'chars', 'bytes', 'sha256'}
                and item['state'] in _STREAM_NAME_STATES)
            check((item['chars'] is None or integer(item['chars'], _STREAM_MAX_PAYLOAD_BYTES))
                and (item['bytes'] is None or integer(item['bytes'], _STREAM_MAX_PAYLOAD_BYTES))
                and (item['sha256'] is None or hashed(item['sha256'])))
            if item['state'] == 'TOKEN':
                check(type(item['token']) is str and _STREAM_TOKEN.fullmatch(item['token']) is not None
                    and item['chars'] == item['bytes'] == len(item['token'])
                    and item['sha256'] == _stream_sha(item['token'].encode('ascii')))
            else:
                check(item['token'] is None)
        check(type(value) is dict and value.get('schema') in (_STREAM_SCHEMA, _STREAM_SCHEMA_V02, _STREAM_SCHEMA_V03))
        v03 = value['schema'] == _STREAM_SCHEMA_V03
        current = value['schema'] in (_STREAM_SCHEMA_V02, _STREAM_SCHEMA_V03)
        if value.get('observation') == 'NOT_OBSERVED':
            check(set(value) == {'schema', 'observation'})
            return dict(value)
        expected_fields = {'schema', 'observation', 'event_ordinal', 'sse_name', 'json_type',
            'name_type_relation', 'json_state', 'json_root_shape', 'payload', 'sequence', 'parser_state', 'links',
            'field_shapes', 'unknown_fields', 'recent_types', 'disposition', 'transport_binding'}
        if current:
            expected_fields.update(('auxiliary_count', 'auxiliary_trace'))
        if v03:
            expected_fields.update(('decoder_resource', 'structure_scope'))
        check(set(value) == expected_fields
            and value['observation'] == 'OBSERVED' and integer(value['event_ordinal'], 8193)
            and value['event_ordinal'] > 0)
        name(value['sse_name']); name(value['json_type'])
        check(value['name_type_relation'] in ('JSON_TYPE_MISSING', 'MALFORMED', 'SSE_NAME_ABSENT', 'MATCH', 'MISMATCH')
            and value['json_state'] in (('PARSED', 'MALFORMED_JSON', 'FRAMING_REFUSED', 'DECODER_RESOURCE_REFUSED')
                if v03 else ('PARSED', 'MALFORMED_JSON', 'FRAMING_REFUSED')))
        check(value['json_root_shape'] in _STREAM_SHAPES + ('NOT_PARSED',))
        if v03:
            check(value['structure_scope'] in ('COMPLETE_EVENT', 'PARSED_PREFIX', 'NOT_PARSED')
                and ((value['structure_scope'] == 'COMPLETE_EVENT') == (value['json_state'] == 'PARSED'))
                and ((value['structure_scope'] == 'NOT_PARSED') == (value['json_root_shape'] == 'NOT_PARSED')))
            if value['structure_scope'] == 'PARSED_PREFIX':
                check(value['json_state'] == 'DECODER_RESOURCE_REFUSED'
                    and value['json_root_shape'] in ('OBJECT', 'ARRAY'))
        else:
            check((value['json_state'] == 'PARSED') == (value['json_root_shape'] != 'NOT_PARSED'))
        check(type(value['payload']) is dict and set(value['payload']) == {'bytes', 'sha256'}
            and integer(value['payload']['bytes'], _STREAM_MAX_PAYLOAD_BYTES) and hashed(value['payload']['sha256']))
        sequence = value['sequence']
        check(type(sequence) is dict and set(sequence) == {'shape', 'value', 'relation'}
            and sequence['shape'] in _STREAM_SHAPES and (sequence['value'] is None or integer(sequence['value'], 2**63 - 1))
            and sequence['relation'] in ('INCREASING', 'NOT_INCREASING', 'MALFORMED'))
        state = value['parser_state']
        check(type(state) is dict and set(state) == {'phase', *_STREAM_COUNT_KEYS}
            and state['phase'] in ('BEFORE_RESPONSE', 'ACTIVE')
            and all(integer(state[key], 8192) for key in _STREAM_COUNT_KEYS))
        links = value['links']
        check(type(links) is dict and set(links) == {'response_relation', 'response_id_sha256', 'item_relation',
            'item_id_sha256', 'output_index', 'content_index', 'summary_index', 'annotation_index'}
            and links['response_relation'] in ('ABSENT', 'MALFORMED', 'CURRENT_NOT_CREATED', 'MATCH', 'MISMATCH')
            and links['item_relation'] in ('ABSENT', 'MALFORMED', 'NOT_REGISTERED', 'MATCH', 'MISMATCH')
            and all(links[key] is None or hashed(links[key]) for key in ('response_id_sha256', 'item_id_sha256'))
            and all(links[key] is None or integer(links[key], 63)
                for key in ('output_index', 'content_index', 'summary_index', 'annotation_index')))
        check(type(value['field_shapes']) is dict
            and set(value['field_shapes']) == set(_STREAM_FIELDS_V02 if current else _STREAM_FIELDS)
            and all(item in (_STREAM_SHAPES + ('NOT_INSPECTED',) if v03 else _STREAM_SHAPES)
                for item in value['field_shapes'].values()))
        if v03 and value['structure_scope'] != 'PARSED_PREFIX':
            check(all(item != 'NOT_INSPECTED' for item in value['field_shapes'].values()))
        unknown = value['unknown_fields']
        check(type(unknown) is dict and set(unknown) == ({'count', 'names_sha256', 'shape_counts', 'inspection_complete'}
                if v03 else {'count', 'names_sha256', 'shape_counts'})
            and integer(unknown['count'], _STREAM_MAX_PAYLOAD_BYTES) and hashed(unknown['names_sha256'])
            and type(unknown['shape_counts']) is dict and set(unknown['shape_counts']) == set(_STREAM_SHAPES)
            and all(integer(item, _STREAM_MAX_PAYLOAD_BYTES) for item in unknown['shape_counts'].values())
            and sum(unknown['shape_counts'].values()) == unknown['count'])
        if v03:
            check(type(unknown['inspection_complete']) is bool
                and unknown['inspection_complete'] == (value['structure_scope'] == 'COMPLETE_EVENT'))
        check(type(value['recent_types']) is list and 1 <= len(value['recent_types']) <= _STREAM_RECENT_TYPE_COUNT)
        for item in value['recent_types']:
            name(item)
        check(value['disposition'] in ('OBSERVED_PREDISPATCH', 'REFUSED', 'COMPLETED'))
        binding = value['transport_binding']
        if binding is not None:
            check(type(binding) is dict and set(binding) == {'reservation_id', 'source_identity_sha256',
                'context_sha256', 'body_sha256', 'response_id_sha256'}
                and type(binding['reservation_id']) is str
                and _stream_re.fullmatch(r'radik-call:[0-9a-f]{32}', binding['reservation_id']) is not None
                and all(hashed(binding[key]) for key in ('source_identity_sha256', 'context_sha256', 'body_sha256'))
                and (binding['response_id_sha256'] is None or hashed(binding['response_id_sha256'])))
        def resource(item, *, decoder=False):
            check(type(item) is dict and set(item) == {'limit_kind', 'measurement', 'value',
                'relation', 'limit', 'traversal_complete'} and type(item['traversal_complete']) is bool)
            if decoder:
                check(item['limit_kind'] == 'JSON_INTEGER_DIGITS' and item['measurement'] == 'DECIMAL_DIGITS'
                    and item['limit'] == 4300 and integer(item['value'], _STREAM_MAX_PAYLOAD_BYTES)
                    and item['value'] > 4300 and item['relation'] == 'EXACT'
                    and item['traversal_complete'] is False)
            else:
                check(item['limit_kind'] == 'AUXILIARY_CANONICAL_BYTES'
                    and item['measurement'] == 'CANONICAL_UTF8_BYTES' and item['limit'] == 16384
                    and integer(item['value'], 16385)
                    and ((item['traversal_complete'] is True and item['relation'] == 'EXACT'
                        and item['value'] <= 16384) or (item['traversal_complete'] is False
                        and item['relation'] == 'LOWER_BOUND' and item['value'] == 16385)))
        if v03:
            if value['decoder_resource'] is not None:
                resource(value['decoder_resource'], decoder=True)
            check((value['json_state'] == 'DECODER_RESOURCE_REFUSED') == (value['decoder_resource'] is not None))
        if current:
            check(integer(value['auxiliary_count'], 8193) and type(value['auxiliary_trace']) is list
                and len(value['auxiliary_trace']) == min(2, value['auxiliary_count']))
            previous = 0
            for item in value['auxiliary_trace']:
                item_fields = {'event_ordinal', 'metadata_shape', 'metadata_bytes', 'metadata_sha256',
                    'auxiliary_bytes', 'auxiliary_sha256', 'known_shapes', 'header_shapes',
                    'unknown_fields', 'categories', 'refusal'}
                if v03:
                    item_fields.update(('resource', 'known_refusals', 'known_inspection_complete'))
                check(type(item) is dict and set(item) == item_fields and integer(item['event_ordinal'], value['event_ordinal'])
                    and item['event_ordinal'] > previous and item['metadata_shape'] in (_STREAM_SHAPES + ('NOT_INSPECTED',) if v03 else _STREAM_SHAPES))
                previous = item['event_ordinal']
                for prefix in ('metadata', 'auxiliary'):
                    check((item[prefix + '_bytes'] is None and item[prefix + '_sha256'] is None)
                        or (integer(item[prefix + '_bytes'], _STREAM_MAX_PAYLOAD_BYTES + 1024)
                            and hashed(item[prefix + '_sha256'])))
                check(type(item['known_shapes']) is dict and set(item['known_shapes']) == set(_STREAM_METADATA_KEYS)
                    and all(shape in (_STREAM_SHAPES + ('NOT_INSPECTED',) if v03 else _STREAM_SHAPES)
                        for shape in item['known_shapes'].values()))
                check(type(item['header_shapes']) is dict and set(item['header_shapes']) == set(_STREAM_METADATA_HEADERS)
                    and all(shape in _STREAM_SHAPES + (('MULTIPLE', 'NOT_INSPECTED') if v03 else ('MULTIPLE',))
                        for shape in item['header_shapes'].values()))
                unknown = item['unknown_fields']
                check(type(unknown) is dict and set(unknown) == ({'count', 'names_sha256', 'shape_counts', 'inspection_complete'}
                        if v03 else {'count', 'names_sha256', 'shape_counts'})
                    and integer(unknown['count'], _STREAM_MAX_PAYLOAD_BYTES) and hashed(unknown['names_sha256'])
                    and type(unknown['shape_counts']) is dict and set(unknown['shape_counts']) == set(_STREAM_SHAPES)
                    and all(integer(number, _STREAM_MAX_PAYLOAD_BYTES) for number in unknown['shape_counts'].values())
                    and sum(unknown['shape_counts'].values()) == unknown['count'])
                categories = item['categories']
                allowed = dict(model=('ABSENT', 'MALFORMED', 'MATCH_REQUEST', 'CONFLICT'),
                    verification=('ABSENT', 'MALFORMED', 'REQUIRES_UNSUPPORTED_VERIFICATION', 'NO_RECOGNIZED_REQUIREMENT'),
                    moderation=('ABSENT', 'PRESENT_OPAQUE'), buffering=('ABSENT', 'INACTIVE', 'MALFORMED',
                        'RETRY_MODEL_REQUESTED', 'PASSIVE_NOTIFICATION'), turn_state=('ABSENT', 'PRESENT_OPAQUE'),
                    control=('ABSENT', 'CONFLICT', 'UNSUPPORTED'))
                if v03:
                    allowed = {key: choices + ('NOT_INSPECTED',) for key, choices in allowed.items()}
                    check(type(item['known_inspection_complete']) is bool
                        and type(unknown['inspection_complete']) is bool
                        and unknown['inspection_complete'] == item['known_inspection_complete']
                        and type(item['known_refusals']) is list
                        and len(item['known_refusals']) <= len(_STREAM_METADATA_REFUSALS)
                        and len(set(item['known_refusals'])) == len(item['known_refusals'])
                        and all(code in _STREAM_METADATA_REFUSALS and code != 'plan_metadata_bound'
                            for code in item['known_refusals']))
                    if item['resource'] is not None:
                        resource(item['resource'])
                        check(item['known_inspection_complete'] is True)
                        if item['resource']['traversal_complete']:
                            check(item['auxiliary_bytes'] == item['resource']['value'])
                        else:
                            check(item['auxiliary_bytes'] is None and item['auxiliary_sha256'] is None
                                and item['refusal'] == 'plan_metadata_byte_limit')
                    if item['known_inspection_complete'] is False:
                        check(item['resource'] is None and all(item[key] is None for key in
                            ('metadata_bytes', 'metadata_sha256', 'auxiliary_bytes', 'auxiliary_sha256')))
                    else:
                        check(all(choice != 'NOT_INSPECTED' for choice in categories.values())
                            and item['metadata_shape'] != 'NOT_INSPECTED'
                            and all(shape != 'NOT_INSPECTED' for shape in item['known_shapes'].values())
                            and all(shape != 'NOT_INSPECTED' for shape in item['header_shapes'].values()))
                check(type(categories) is dict and set(categories) == set(allowed)
                    and all(categories[key] in choices for key, choices in allowed.items())
                    and item['refusal'] in (None, *(_STREAM_METADATA_REFUSALS_V03 if v03 else _STREAM_METADATA_REFUSALS)))
        raw = _stream_canonical(value)
        check(len(raw) <= _STREAM_MAX_OBSERVATION_BYTES)
        return _stream_json.loads(raw)
    except (ValueError, TypeError, KeyError, OverflowError, UnicodeError, RecursionError):
        return None

